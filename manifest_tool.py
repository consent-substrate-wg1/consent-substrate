def run_ed25519_vectors(verbose: bool = True) -> tuple:
    """Returns (passed, total). Covers derive, sign, verify, tamper-reject,
    PEM interop and PEM roundtrip. No network, no third-party imports."""
    ok = 0
    total = 0
    for name, seed, msg, pub, sig in _VECTORS:
        seed_b, msg_b = bytes.fromhex(seed), bytes.fromhex(msg)
        pub_b, sig_b = bytes.fromhex(pub), bytes.fromhex(sig)
        good = True
        key = PureEd25519PrivateKey(seed_b)
        good &= key.public_key().public_bytes_raw() == pub_b      # derive
        good &= key.sign(msg_b) == sig_b                          # sign
        total += 1
        if good:
            ok += 1
        good = True
        try:
            PureEd25519PublicKey(pub_b).verify(sig_b, msg_b)      # verify
        except Exception:
            good = False
        try:
            bad = bytearray(sig_b)
            bad[0] ^= 1
            PureEd25519PublicKey(pub_b).verify(bytes(bad), msg_b)  # tamper
            good = False                                           # must raise
        except InvalidSignature:
            pass
        except Exception:
            good = False
        total += 1
        if good:
            ok += 1
        if verbose:
            print(f"  [{'PASS' if good else 'FAIL'}] {name}: "
                  f"derive/sign/verify/tamper-reject")
    # PEM interop: load the oracle-written PKCS8 wrapper for the TEST1 seed.
    total += 1
    good = True
    try:
        k = load_pem_private_key(_pem(_ORACLE_PKCS8, "PRIVATE KEY"))
        good &= k.sign(b"") == bytes.fromhex(_VECTORS[0][4])
        good &= k.public_key().public_bytes_raw() == _ORACLE_SPKI[12:]
    except Exception:
        good = False
    if good:
        ok += 1
    if verbose:
        print(f"  [{'PASS' if good else 'FAIL'}] PKCS8 interop "
              f"(cryptography-written wrapper)")
    # PEM roundtrip: fresh key -> PEM -> load -> same public key + signature.
    total += 1
    good = True
    try:
        k2 = PureEd25519PrivateKey.generate()
        reloaded = load_pem_private_key(k2.private_bytes_pem())
        m = b"roundtrip"
        good &= reloaded.public_key().public_bytes_raw() == \
            k2.public_key().public_bytes_raw()
        good &= reloaded.sign(m) == k2.sign(m)
    except Exception:
        good = False
    if good:
        ok += 1
    if verbose:
        print(f"  [{'PASS' if good else 'FAIL'}] PKCS8 roundtrip "
              f"(fresh key -> PEM -> load)")
    return ok, total


MANIFEST_VERSION = "1.0"
MAX_VALIDITY_DAYS = 90
SIGNATURE_ALG = "ed25519"

# The allowlist of actions a manifest can authorize. Anything not listed
# here cannot appear in allowed_actions (structural refusal at signing,
# DENY at runtime). The enum itself is the wall.
KNOWN_ACTIONS = (
    "read_public",         # fetch what an anonymous visitor can reach
    "probe",               # active existence checks (HEAD/OPTIONS, known paths)
    "fingerprint",         # identify tech, versions, headers
    "api_discovery",       # enumerate documented surface (OpenAPI, robots, docs)
    "authenticated_scan",  # scan with credentials the OWNER provided (by handle)
    "injection_test",      # benign canary payloads; detect reflection/handling
    "exploit_poc",         # minimal PoC; needs poc_consent + bug_bounty block
)

# Structural prohibitions: NEVER authorizable by any manifest. They are
# absent from KNOWN_ACTIONS on purpose.
CORE_FORBIDDEN = frozenset({
    "denial_of_service",
    "credential_stuffing",
    "brute_force",
    "social_engineering",
    "data_exfiltration",
    "destructive_ops",
    "persistence",          # no implants, no backdoors, no dead-man switches
    "lateral_movement",
})

# Pragmatic hostname check: 2+ labels, no wildcards, no spaces.
_DOMAIN_RE = re.compile(r"^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?(\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)+$")
_URLISH_RE = re.compile(r"^https?://[a-z0-9.\-]+(:\d+)?(/.*)?$")


