# --------------------------------------------------------------------------
# Ed25519 (RFC 8032) - pure stdlib, no third-party imports anywhere.
#
# The zero-dependency property is a published claim of this project (README,
# RELEASE_NOTES, the paper's reproduction protocol), so signing MUST work on
# a bare interpreter: no `cryptography`, no pip, no network. Deterministic
# signatures are byte-identical to RFC-conformant implementations; the
# `ed25519-vectors` subcommand validates against RFC 8032 test vectors (the
# first two vectors are the published RFC values) plus PKCS8/SPKI interop
# with keys generated by the `cryptography` package.
#
# Not constant-time. Threat model: owner-held signing keys on the owner's
# lab host -- same posture as the previous implementation.
# --------------------------------------------------------------------------

class InvalidSignature(Exception):
    """Raised when an Ed25519 signature does not verify."""


_P = 2**255 - 19
_L = 2**252 + 27742317777372353535851937790883648493
_D = (-121665 * pow(121666, _P - 2, _P)) % _P
_SQRTM1 = pow(2, (_P - 1) // 4, _P)


def _sha512(b: bytes):
    return hashlib.sha512(b)


def _recover_x(y: int, sign: int) -> tuple:
    """Decompress an Edwards y into extended (X, Y, Z, T). Fail-closed."""
    if y >= _P:
        raise InvalidSignature("non-canonical y encoding")
    u = (y * y - 1) % _P
    v = (_D * y * y + 1) % _P
    x = u * pow(v, 3, _P) % _P * pow(u * pow(v, 7, _P) % _P, (_P - 5) // 8, _P) % _P
    x2v = x * x % _P * v % _P
    if x2v == u:
        pass
    elif x2v == (-u) % _P:
        x = x * _SQRTM1 % _P
    else:
        raise InvalidSignature("point not on curve")
    if x == 0 and sign:
        raise InvalidSignature("non-canonical x sign")
    if (x & 1) != sign:
        x = _P - x
    return (x, y, 1, x * y % _P)


_B = _recover_x((4 * pow(5, _P - 2, _P)) % _P, 0)


def _pt_add(p: tuple, q: tuple) -> tuple:
    """Unified addition (add-2008-hwcd-3) for a=-1 twisted Edwards."""
    x1, y1, z1, t1 = p
    x2, y2, z2, t2 = q
    a = (y1 - x1) * (y2 - x2) % _P
    b = (y1 + x1) * (y2 + x2) % _P
    c = 2 * _D * t1 * t2 % _P
    d = 2 * z1 * z2 % _P
    e, f, g, h = b - a, d - c, d + c, b + a
    return (e * f % _P, g * h % _P, f * g % _P, e * h % _P)


def _mul(s: int, p: tuple) -> tuple:
    q = (0, 1, 1, 0)                       # neutral element
    while s > 0:
        if s & 1:
            q = _pt_add(q, p)
        p = _pt_add(p, p)
        s >>= 1
    return q


def _compress(p: tuple) -> bytes:
    x, y, z, _ = p
    zi = pow(z, _P - 2, _P)
    x = x * zi % _P
    y = y * zi % _P
    return (y | ((x & 1) << 255)).to_bytes(32, "little")


def _clamp(seed: bytes) -> tuple:
    h = _sha512(seed).digest()
    a = bytearray(h[:32])
    a[0] &= 248
    a[31] &= 127
    a[31] |= 64
    return int.from_bytes(a, "little"), h[32:]


def _sign(seed: bytes, msg: bytes) -> tuple:
    a, prefix = _clamp(seed)
    pub = _compress(_mul(a, _B))
    r = int.from_bytes(_sha512(prefix + msg).digest(), "little") % _L
    rb = _compress(_mul(r, _B))
    k = int.from_bytes(_sha512(rb + pub + msg).digest(), "little") % _L
    s = (r + k * a) % _L
    return pub, rb + s.to_bytes(32, "little")


class PureEd25519PrivateKey:
    """Seed-backed Ed25519 private key (RFC 8032 5.1.5)."""

    def __init__(self, seed: bytes):
        seed = bytes(seed)
        if len(seed) != 32:
            raise ValueError("Ed25519 seed must be exactly 32 bytes")
        self._seed = seed

    @classmethod
    def generate(cls) -> "PureEd25519PrivateKey":
        return cls(os.urandom(32))

    @classmethod
    def from_private_bytes(cls, seed: bytes) -> "PureEd25519PrivateKey":
        return cls(seed)

    def public_key(self) -> "PureEd25519PublicKey":
        return PureEd25519PublicKey(_compress(_mul(_clamp(self._seed)[0], _B)))

    def sign(self, msg: bytes) -> bytes:
        return _sign(self._seed, bytes(msg))[1]

    def private_bytes_pem(self) -> bytes:
        return _pem(_PKCS8_PREFIX + self._seed, "PRIVATE KEY")


class PureEd25519PublicKey:
    """Raw 32-byte Ed25519 public key; verify() raises InvalidSignature."""

    def __init__(self, raw: bytes):
        raw = bytes(raw)
        if len(raw) != 32:
            raise ValueError("Ed25519 public key must be exactly 32 bytes")
        self._raw = raw

    @classmethod
    def from_public_bytes(cls, raw: bytes) -> "PureEd25519PublicKey":
        return cls(raw)

    def public_bytes_raw(self) -> bytes:
        return self._raw

    def verify(self, signature: bytes, msg: bytes) -> None:
        signature = bytes(signature)
        msg = bytes(msg)
        if len(signature) != 64:
            raise InvalidSignature("signature must be 64 bytes")
        s = int.from_bytes(signature[32:], "little")
        if s >= _L:
            raise InvalidSignature("non-canonical S")
        r_pt = _decompress(signature[:32])
        a_pt = _decompress(self._raw)
        k = int.from_bytes(_sha512(signature[:32] + self._raw + msg).digest(),
                           "little") % _L
        lhs = _mul(s, _B)
        rhs = _pt_add(r_pt, _mul(k, a_pt))
        if (lhs[0] * rhs[2] - rhs[0] * lhs[2]) % _P != 0 or \
           (lhs[1] * rhs[2] - rhs[1] * lhs[2]) % _P != 0:
            raise InvalidSignature("Ed25519 signature INVALID")


def _decompress(b: bytes) -> tuple:
    if len(b) != 32:
        raise InvalidSignature("bad point encoding")
    val = int.from_bytes(b, "little")
    return _recover_x(val & ((1 << 255) - 1), val >> 255)


# Fixed DER wrappers: Ed25519 PKCS8 private and SPKI public. These are the
# exact encodings the `cryptography` package writes, so keys generated before
# the zero-dependency switch keep working unchanged.
_PKCS8_PREFIX = bytes.fromhex("302e020100300506032b657004220420")
_SPKI_PREFIX = bytes.fromhex("302a300506032b6570032100")


def _pem(der: bytes, kind: str) -> bytes:
    b64 = base64.b64encode(der).decode("ascii")
    lines = [b64[i:i + 64] for i in range(0, len(b64), 64)]
    armor = "-----BEGIN %s-----" % kind
    armor_end = "-----END %s-----" % kind
    return ("\n".join([armor] + lines + [armor_end]) + "\n").encode("ascii")


def _der_from_pem(blob: bytes) -> bytes:
    try:
        text = bytes(blob).decode("ascii")
    except UnicodeDecodeError:
        raise ValueError("not a PEM text")
    if not any(l.startswith("-----BEGIN ") for l in text.splitlines()):
        raise ValueError("missing PEM armor")
    body = "".join(l.strip() for l in text.splitlines()
                   if not l.startswith("-----"))
    try:
        return base64.b64decode(body, validate=True)
    except Exception:
        raise ValueError("invalid PEM base64")


def load_pem_private_key(data: bytes, password=None) -> PureEd25519PrivateKey:
    if password is not None:
        raise ValueError("encrypted private keys are not supported")
    der = _der_from_pem(data)
    if len(der) != 48 or der[:16] != _PKCS8_PREFIX:
        raise ValueError("not an unencrypted Ed25519 PKCS8 private key")
    return PureEd25519PrivateKey(der[16:48])


def load_pem_public_key(blob: bytes) -> PureEd25519PublicKey:
    der = _der_from_pem(blob)
    if len(der) != 44 or der[:12] != _SPKI_PREFIX:
        raise ValueError("not an Ed25519 SPKI public key PEM")
    return PureEd25519PublicKey(der[12:44])


